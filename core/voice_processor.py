    # ============================================================
    # ОСНОВНАЯ ОБРАБОТКА
    # ============================================================
    def process(self, text: str) -> str:
        if not text:
            return ""

        # 1. ограничение длины
        if len(text) > self.settings["max_length"]:
            text = text[: self.settings["max_length"]] + "..."

        # 2. смайлы (до чистки спецсимволов)
        if self.settings["speak_emoji"]:
            for emoji, word in self.emoji_map.items():
                text = text.replace(emoji, f" {word} ")

        # 3. английские слова (по длине — длинные первыми)
        if self.settings["speak_english"]:
            for eng, rus in sorted(self.eng_map.items(),
                                   key=lambda x: len(x[0]), reverse=True):
                text = re.sub(r"\b" + re.escape(eng) + r"\b", rus,
                              text, flags=re.IGNORECASE)

        # 4. цифры (по длине — длинные первыми)
        if self.settings["speak_numbers"]:
            for num, word in sorted(self.digit_map.items(),
                                    key=lambda x: len(x[0]), reverse=True):
                text = re.sub(r"\b" + re.escape(num) + r"\b", word, text)

        # 5. удаление спецсимволов
        if self.settings["remove_special"]:
            text = re.sub(r"[^\w\s\.\,\!\?\-\:\(\)]", " ", text)

        # 6. лишние пробелы
        text = re.sub(r"\s+", " ", text).strip()
        return text

    # ============================================================
    # НАСТРОЙКИ
    # ============================================================
